public struct ExportRequest: Sendable {
    public let screenshot: CGImage?
    public let reference: CGImage?
    public let title: String
    public let marks: [ReviewMark]
    public let videoURL: URL?
    public let loopStart: Double?
    public let loopEnd: Double?
    public let parent: URL
    public let wireframe: LayoutOverlay?

    public init(screenshot: CGImage?, reference: CGImage?, title: String, marks: [ReviewMark],
                videoURL: URL?, loopStart: Double?, loopEnd: Double?, parent: URL, wireframe: LayoutOverlay? = nil) {
        self.screenshot = screenshot; self.reference = reference; self.title = title; self.marks = marks
        self.videoURL = videoURL; self.loopStart = loopStart; self.loopEnd = loopEnd; self.parent = parent
        self.wireframe = wireframe
    }
}
