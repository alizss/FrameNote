import Foundation
import CoreGraphics

public enum MarkKind: String, Codable, CaseIterable, Identifiable, Sendable {
    case point = "Pin"
    case arrow = "Arrow"
    case measure = "Measure gap"
    case guideHorizontal = "Horizontal guide"
    case guideVertical = "Vertical guide"
    case focus = "Focus area"
    case move = "Move here"
    case compareGaps = "Compare gaps"

    public var id: String { rawValue }
}

public struct UnitPoint2D: Codable, Equatable, Sendable {
    public var x: Double
    public var y: Double

    public init(x: Double, y: Double) {
        self.x = min(max(x, 0), 1)
        self.y = min(max(y, 0), 1)
    }
}

public struct ReviewMark: Codable, Identifiable, Equatable, Sendable {
    public var id: UUID
    public var kind: MarkKind
    public var start: UnitPoint2D
    public var end: UnitPoint2D?
    public var secondStart: UnitPoint2D?
    public var secondEnd: UnitPoint2D?
    public var time: Double?
    public var endTime: Double?
    public var approved: Bool?
    public var isApproved: Bool {
        get { approved ?? false }
        set { approved = newValue ? true : nil }
    }
    public var note: String
    /// True for annotations FrameNote generated by measuring the layout; the person can edit, approve or delete them.
    public var auto: Bool?
    public var inspirations: [InspirationAttachment]?
    public var wholeMedia: Bool?
    public var aiGenerated: Bool?
    public var designAnalysis: String?
    public var variants: [ReviewVariant]?
    public var selectedVariantID: UUID?
    public var understanding: DesignUnderstanding?
    public var visualSuggestionFile: String?
    public var realExamples: [FoundExample]?
    public var exampleSummary: String?

    public init(id: UUID = UUID(), kind: MarkKind, start: UnitPoint2D, end: UnitPoint2D? = nil,
                secondStart: UnitPoint2D? = nil, secondEnd: UnitPoint2D? = nil,
                time: Double? = nil, endTime: Double? = nil, note: String) {
        self.id = id
        self.kind = kind
        self.start = start
        self.end = end
        self.secondStart = secondStart
        self.secondEnd = secondEnd
        self.time = time
        self.endTime = endTime
        self.note = note
    }

    public func isVisible(at currentTime: Double?) -> Bool {
        if wholeMedia == true { return false }
        guard let currentTime, let time else { return true }
        if let endTime { return currentTime >= time - 0.03 && currentTime <= endTime + 0.03 }
        return abs(time - currentTime) < 0.18
    }

    /// An annotation for a measured finding. Uneven spacing becomes a gap comparison; everything else a highlighted area.
    public init(finding: LayoutFinding, time: Double?) {
        func point(_ value: CGPoint) -> UnitPoint2D { UnitPoint2D(x: value.x, y: value.y) }
        if finding.category == .spacing, let a = finding.gapA, let b = finding.gapB {
            self.init(kind: .compareGaps, start: point(a.from), end: point(a.to),
                      secondStart: point(b.from), secondEnd: point(b.to), time: time, note: finding.note)
        } else {
            self.init(kind: .focus, start: point(CGPoint(x: finding.rect.minX, y: finding.rect.minY)),
                      end: point(CGPoint(x: finding.rect.maxX, y: finding.rect.maxY)), time: time, note: finding.note)
        }
        auto = true
    }

    /// Changes the mark's type while keeping its comment, time and attachments.
    /// Shapes that need a second point get a visible default; Compare gaps needs two drawn gaps, so it is not a target.
    public mutating func convert(to newKind: MarkKind) {
        guard newKind != kind, newKind != .compareGaps else { return }
        switch newKind {
        case .point, .guideHorizontal, .guideVertical:
            if let end { start = UnitPoint2D(x: (start.x + end.x) / 2, y: (start.y + end.y) / 2) }
            end = nil
        case .focus, .arrow, .move, .measure:
            if end == nil {
                let x = start.x, y = start.y
                switch newKind {
                case .focus:
                    start = UnitPoint2D(x: x - 0.08, y: y - 0.06)
                    end = UnitPoint2D(x: x + 0.08, y: y + 0.06)
                case .arrow:
                    // Points at the old pin position.
                    start = UnitPoint2D(x: x > 0.5 ? x - 0.12 : x + 0.12, y: y > 0.5 ? y - 0.12 : y + 0.12)
                    end = UnitPoint2D(x: x, y: y)
                default:
                    end = UnitPoint2D(x: x > 0.85 ? x - 0.12 : x + 0.12, y: y)
                }
            }
        case .compareGaps:
            return
        }
        secondStart = nil
        secondEnd = nil
        kind = newKind
    }

    public func distanceInPixels(width: Int, height: Int) -> Double? {
        guard let end else { return nil }
        let dx = (end.x - start.x) * Double(width)
        let dy = (end.y - start.y) * Double(height)
        return hypot(dx, dy)
    }

    public func secondDistanceInPixels(width: Int, height: Int) -> Double? {
        guard let secondStart, let secondEnd else { return nil }
        let dx = (secondEnd.x - secondStart.x) * Double(width)
        let dy = (secondEnd.y - secondStart.y) * Double(height)
        return hypot(dx, dy)
    }
}

public struct DesignUnderstanding: Codable, Equatable, Sendable {
    public var observation: String
    public var evidence: String
    public var focusStart: UnitPoint2D?
    public var focusEnd: UnitPoint2D?
    public var timeStart: Double?
    public var timeEnd: Double?

    public init(observation: String, evidence: String, focusStart: UnitPoint2D? = nil,
                focusEnd: UnitPoint2D? = nil, timeStart: Double? = nil, timeEnd: Double? = nil) {
        self.observation = observation; self.evidence = evidence
        self.focusStart = focusStart; self.focusEnd = focusEnd
        self.timeStart = timeStart; self.timeEnd = timeEnd
    }
}

public struct FoundExample: Codable, Identifiable, Equatable, Sendable {
    public var id: String { url }
    public var title: String
    public var url: String

    public init(title: String, url: String) { self.title = title; self.url = url }
}

public struct InspirationAttachment: Codable, Identifiable, Equatable, Sendable {
    public enum Kind: String, Codable, Sendable { case url, image, video }
    public var id: UUID
    public var kind: Kind
    /// A web URL or a local file URL. Exported manifests use paths inside the review folder.
    public var value: String
    public var displayName: String?

    public init(id: UUID = UUID(), kind: Kind, value: String, displayName: String? = nil) {
        self.id = id; self.kind = kind; self.value = value; self.displayName = displayName
    }
}

public struct ReviewManifest: Codable, Sendable {
    public var schemaVersion: Int
    public var createdAt: Date
    public var title: String
    public var imageWidth: Int
    public var imageHeight: Int
    public var imageFile: String
    public var annotatedImageFile: String
    /// Screenshot with the detected layout (boxes and shared edges) drawn over it; still images only.
    public var wireframeImageFile: String?
    public var referenceImageFile: String?
    public var videoFile: String?
    public var loopStart: Double?
    public var loopEnd: Double?
    public var marks: [ReviewMark]
    public var motionEvidence: [MotionEvidence]?

    public init(createdAt: Date, title: String, imageWidth: Int, imageHeight: Int,
                referenceImageFile: String?, videoFile: String? = nil,
                loopStart: Double? = nil, loopEnd: Double? = nil, marks: [ReviewMark]) {
        self.schemaVersion = 1
        self.createdAt = createdAt
        self.title = title
        self.imageWidth = imageWidth
        self.imageHeight = imageHeight
        self.imageFile = "screenshot.png"
        self.annotatedImageFile = "annotated.png"
        self.referenceImageFile = referenceImageFile
        self.videoFile = videoFile
        self.loopStart = loopStart
        self.loopEnd = loopEnd
        self.marks = marks
    }
}

public enum ReviewMarkdown {
    public static func generate(_ manifest: ReviewManifest) -> String {
        var lines = [
            "# \(manifest.title)",
            "",
            "Source: `screenshot.png`  ·  Marked view: `annotated.png`",
        ]
        if manifest.referenceImageFile != nil {
            lines.append("Reference: `reference.png`")
        }
        if let wireframe = manifest.wireframeImageFile {
            lines.append("Wireframe: `\(wireframe)` — purple boxes are detected elements, purple lines are edges several elements share")
        }
        if let videoFile = manifest.videoFile {
            lines[2] = "Source video: `\(videoFile)`"
        }
        if let start = manifest.loopStart, let end = manifest.loopEnd {
            lines.append("Loop: \(timecode(start))–\(timecode(end))")
        }
        lines += ["", "Image: \(manifest.imageWidth) × \(manifest.imageHeight) pixels", "", "## Feedback", ""]
        if manifest.marks.isEmpty {
            lines.append("No marks added.")
        }
        for (index, mark) in manifest.marks.enumerated() {
            let position = mark.wholeMedia == true ? "whole frame" : "(\(Int((mark.start.x * 100).rounded()))%, \(Int((mark.start.y * 100).rounded()))%)"
            let time = mark.time.map { " at \(timecode($0))" + (mark.endTime.map { "–\(timecode($0))" } ?? "") } ?? ""
            let distance = mark.kind == .measure
                ? mark.distanceInPixels(width: manifest.imageWidth, height: manifest.imageHeight).map { " · ≈\(Int($0.rounded())) px" } ?? ""
                : ""
            let note = mark.note.trimmingCharacters(in: .whitespacesAndNewlines)
            var detail = ""
            if mark.kind == .compareGaps,
               let first = mark.distanceInPixels(width: manifest.imageWidth, height: manifest.imageHeight),
               let second = mark.secondDistanceInPixels(width: manifest.imageWidth, height: manifest.imageHeight) {
                detail = " · A ≈\(Int(first.rounded())) px, B ≈\(Int(second.rounded())) px (Δ \(Int(abs(first - second).rounded())) px)"
            }
            var frame = manifest.videoFile == nil ? "" : " · `moment-\(String(format: "%02d", index + 1))-marked.png`"
            if let evidence = manifest.motionEvidence?.first(where: { $0.markID == mark.id }) {
                frame += " · Sequence: `\(evidence.sequenceFile)` · Clip: `\(evidence.clipFile)`"
            }
            if mark.kind == .focus {
                let focusFile = manifest.videoFile == nil
                    ? String(format: "focus-%02d.png", index + 1)
                    : String(format: "moment-%02d-focus.png", index + 1)
                frame += " · Focus crop: `\(focusFile)`"
            }
            let approval = (mark.isApproved ? " [Approved — no change needed]" : "") + (mark.auto == true ? " [Auto-detected from pixels]" : "")
            lines.append("\(index + 1).\(approval) **\(mark.kind.rawValue)** at \(position)\(time)\(distance)\(detail)\(frame): \(note.isEmpty ? (mark.wholeMedia == true ? "Study this reference. Explain what works and suggest concrete ideas to adapt, grounded in the visual evidence." : "Describe the change here.") : note)")
            for inspiration in mark.inspirations ?? [] {
                lines.append("   - Inspiration: \(inspiration.displayName.map { "\($0) — " } ?? "")\(inspiration.value)")
            }
            if let analysis = mark.designAnalysis, !analysis.isEmpty {
                lines.append("   - Design analysis: \(analysis.replacingOccurrences(of: "\n", with: " "))")
            }
            for variant in mark.variants ?? [] {
                let selected = variant.id == mark.selectedVariantID
                lines.append("   - \(selected ? "Selected" : "Alternative") prototype \(variant.version): `\(variant.filename)` — \(variant.title)")
                if selected { lines.append(variant.implementationBrief(note: mark.note)) }
            }
            if let understanding = mark.understanding {
                lines.append("   - AI understood: \(understanding.observation) Evidence: \(understanding.evidence)")
            }
            if let visual = mark.visualSuggestionFile {
                lines.append("   - AI visual concept: `\(visual)`")
            }
            for example in mark.realExamples ?? [] {
                lines.append("   - Real example: \(example.title) — \(example.url)")
            }
        }
        lines += ["", "Marks use coordinates relative to the original screenshot. Review the image and notes together; measurements are screenshot pixels, not necessarily UI points.", ""]
        return lines.joined(separator: "\n")
    }

    private static func timecode(_ seconds: Double) -> String {
        let totalMilliseconds = Int((seconds * 1000).rounded())
        let minutes = totalMilliseconds / 60_000
        let wholeSeconds = (totalMilliseconds / 1000) % 60
        let milliseconds = totalMilliseconds % 1000
        return String(format: "%02d:%02d.%03d", minutes, wholeSeconds, milliseconds)
    }
}

